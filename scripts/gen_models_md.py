"""Write MODELS.md from the registry, so the published list always matches the app.

uv run python scripts/gen_models_md.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from irisecho_core.registry import load

ROOT = Path(__file__).resolve().parents[1]
KIND = {
    "image": "Images",
    "edit": "Edits",
    "upscale": "Upscaling",
    "video": "Video",
    "video-upscale": "Video upscaling (API and command line only)",
    "voice": "Voice",
    "clone": "Voice cloning",
    "music": "Music",
    "sfx": "Sound effects",
    "model3d": "3D models",
    "views3d": "3D helper (front and back views for Pixal3D)",
    "prompt": "Helpers",
}


def size(n: int) -> str:
    gb = n / 2**30
    return f"{gb:.1f} GB" if gb >= 1 else f"{n / 2**20:.0f} MB"


def render() -> str:
    reg = load()
    lines = [
        "# Models",
        "",
        "<!-- Generated by scripts/gen_models_md.py from the registry. Do not edit. -->",
        "",
        "IrisEcho never redistributes model weights. Each file is downloaded from its",
        "publisher's repository, pinned to a commit and checked against a recorded hash,",
        "when you choose to use it. The publisher's license governs your use of the model",
        "and, in some cases, of what it makes.",
        "",
        "Sizes are for an NVIDIA RTX 20/30/40 card (int4 builds); shared files such as text",
        "encoders are counted once per model but downloaded once overall.",
        "",
    ]
    for kind, title in KIND.items():
        models = [m for m in reg.models.values() if m.kind == kind]
        if not models:
            continue
        lines += [
            f"## {title}",
            "",
            "| Model | What it is for | License | Commercial use | Size | Source |",
            "|---|---|---|---|---|---|",
        ]
        for m in models:
            lic = reg.licenses[m.license]
            if lic.condition:
                commercial = lic.condition
            else:
                commercial = "Yes" if lic.commercial else "**No**"
            if lic.gated:
                commercial += " (sign-in required)"
            variant = next(
                (v for v in m.variants if v.when.get("quant", "int4") == "int4"), m.variants[0]
            )
            files = reg.expand(variant.files)
            repos = sorted({f.repo for f in files})
            src = ", ".join(f"[{r}](https://huggingface.co/{r})" for r in repos)
            lines.append(
                f"| {m.name} | {m.summary} | [{lic.name}]({lic.url}) | {commercial} | "
                f"{size(sum(f.size for f in files))} | {src} |"
            )
        lines.append("")
    lines += [
        "## Notes",
        "",
        "- Non-commercial and gated models are opt-in: IrisEcho shows the license and asks",
        "  you to accept it before downloading anything.",
        "- Chatterbox output carries Resemble AI's inaudible Perth watermark. IrisEcho",
        "  keeps it. Only clone voices you have permission to use.",
        "- Stable Audio 3's text encoder is also covered by Google's Gemma Terms of Use.",
        "- TRELLIS.2 and Pixal3D read pictures with Meta's DINOv3 (the file in",
        "  Comfy-Org/Pixal3D), which is under the DINOv3 License; IrisEcho asks you to",
        "  accept it before downloading.",
        "",
    ]
    return "\n".join(lines)


AGENTS = ROOT / "core" / "src" / "irisecho_core" / "AGENTS.md"
START, END = "<!-- controls:start -->", "<!-- controls:end -->"


def _value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if v == [] or v is None or v == "":
        return "none"
    return str(v)


def render_controls() -> str:
    """The advanced-controls table inside AGENTS.md, one row per control."""
    reg = load()
    lines = [
        START,
        "<!-- Generated by scripts/gen_models_md.py from the registry. Do not edit. -->",
        "",
        "| Model | Param | Values | Recommended | What it does |",
        "|---|---|---|---|---|",
    ]
    for m in reg.models.values():
        for c in m.controls:
            if c.type in ("int", "float"):
                values = f"{_value(c.min)} to {_value(c.max)}"
            elif c.type == "choice":
                values = ", ".join(_value(v) for v in c.values())
            elif c.type == "loras":
                shape = "{high, low, strength}" if c.pair else "{file, strength}"
                values = f"up to 3 {shape}, strength -2 to 2"
            else:
                values = c.type
            if c.needs:
                values += f" (with `{c.needs}`)"
            help_text = c.help.replace("|", "/")
            row = [f"`{m.id}`", f"`{c.name}`", values, _value(c.default), f"{c.label}. {help_text}"]
            lines.append("| " + " | ".join(row) + " |")
    lines += ["", END]
    return "\n".join(lines)


def agents_text() -> str:
    text = AGENTS.read_text(encoding="utf-8")
    before, _, rest = text.partition(START)
    _, _, after = rest.partition(END)
    if not rest:
        raise SystemExit(f"{AGENTS} has no {START} ... {END} section")
    return before + render_controls() + after


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    outputs = {ROOT / "MODELS.md": render(), AGENTS: agents_text()}
    if args.check:
        stale = [
            t.name
            for t, text in outputs.items()
            if (t.read_text(encoding="utf-8") if t.exists() else "") != text
        ]
        if stale:
            print(f"{', '.join(stale)} out of date; run scripts/gen_models_md.py", file=sys.stderr)
            return 1
        return 0
    for target, text in outputs.items():
        with open(target, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
